-- 03_inv_ddl.sql : limpieza, tablas, restricciones e indices de las 6 tablas INV/OPS.
--
-- PRERREQUISITOS (deben existir antes de ejecutar):
--   Andy    : TB_CPL_COMPLAINT
--   Leonardo: TB_STAFF_OFFICER, TB_TERR_SECTOR
--
-- ORDEN DE CREACION (por dependencias de FK):
--   INV_ASSIGNMENT -> INV_SUPPORT_TEAM -> INV_STATUS_HISTORY
--   -> OPS_OPERATION -> OPS_OPERATION_COMPLAINT -> OPS_OPERATION_STAFF
-- ===================================================================

/* =====================================================================
   0. LIMPIEZA (solo mis 6 tablas; permite re-ejecutar el script)
   ===================================================================== */
BEGIN
  FOR t IN (SELECT column_value AS tname FROM TABLE(sys.odcivarchar2list(
              'TB_OPS_OPERATION_STAFF','TB_OPS_OPERATION_COMPLAINT','TB_OPS_OPERATION',
              'TB_INV_SUPPORT_TEAM','TB_INV_STATUS_HISTORY','TB_INV_ASSIGNMENT'))) LOOP
    BEGIN
      EXECUTE IMMEDIATE 'DROP TABLE ' || t.tname || ' CASCADE CONSTRAINTS PURGE';
    EXCEPTION WHEN OTHERS THEN
      IF SQLCODE != -942 THEN RAISE; END IF;   -- ORA-00942: la tabla no existe
    END;
  END LOOP;
END;
/

/* =====================================================================
   1. DDL
   ===================================================================== */

-- 1.1 Asignacion del investigador titular (historial de reasignaciones)
CREATE TABLE TB_INV_ASSIGNMENT (
  assignment_id       NUMBER(12)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
  complaint_id        NUMBER(12)   NOT NULL,
  officer_cip         VARCHAR2(15) NOT NULL,
  assigned_by_cip     VARCHAR2(15) NOT NULL,
  assignment_date     TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
  end_date            DATE,
  reassignment_reason VARCHAR2(200),
  CONSTRAINT PK_INV_ASSIGNMENT   PRIMARY KEY (assignment_id),
  CONSTRAINT FK_INVASG_COMPLAINT FOREIGN KEY (complaint_id)
      REFERENCES TB_CPL_COMPLAINT (complaint_id),                 -- ON DELETE RESTRICT (por defecto)
  CONSTRAINT FK_INVASG_OFFICER   FOREIGN KEY (officer_cip)
      REFERENCES TB_STAFF_OFFICER (officer_cip),
  CONSTRAINT FK_INVASG_ASSIGNER  FOREIGN KEY (assigned_by_cip)
      REFERENCES TB_STAFF_OFFICER (officer_cip),
  CONSTRAINT CK_INVASG_DIFF_CIP  CHECK (officer_cip <> assigned_by_cip),
  CONSTRAINT CK_INVASG_DATES     CHECK (end_date IS NULL OR end_date >= TRUNC(assignment_date))
);

-- Un solo PRIMARY activo por denuncia: indice unico basado en funcion.
-- Cuando end_date NO es nulo la expresion devuelve NULL y no entra al indice.
CREATE UNIQUE INDEX UX_INVASG_ACTIVE_PER_COMPLAINT
  ON TB_INV_ASSIGNMENT (CASE WHEN end_date IS NULL THEN complaint_id END);

CREATE INDEX IX_INVASG_OFFICER   ON TB_INV_ASSIGNMENT (officer_cip, end_date);
CREATE INDEX IX_INVASG_COMPLAINT ON TB_INV_ASSIGNMENT (complaint_id);
CREATE INDEX IX_INVASG_ASSIGNER  ON TB_INV_ASSIGNMENT (assigned_by_cip);

-- 1.2 Equipo de apoyo
CREATE TABLE TB_INV_SUPPORT_TEAM (
  complaint_id NUMBER(12)   NOT NULL,
  officer_cip  VARCHAR2(15) NOT NULL,
  CONSTRAINT PK_INV_SUPPORT_TEAM PRIMARY KEY (complaint_id, officer_cip),
  CONSTRAINT FK_INVSUP_COMPLAINT FOREIGN KEY (complaint_id)
      REFERENCES TB_CPL_COMPLAINT (complaint_id),
  CONSTRAINT FK_INVSUP_OFFICER   FOREIGN KEY (officer_cip)
      REFERENCES TB_STAFF_OFFICER (officer_cip)
);
CREATE INDEX IX_INVSUP_OFFICER ON TB_INV_SUPPORT_TEAM (officer_cip);

-- 1.3 Historial inmutable de estados
CREATE TABLE TB_INV_STATUS_HISTORY (
  history_id       NUMBER(14)    GENERATED BY DEFAULT ON NULL AS IDENTITY,
  complaint_id     NUMBER(12)    NOT NULL,
  officer_cip      VARCHAR2(15)  NOT NULL,
  previous_status  VARCHAR2(30),
  new_status       VARCHAR2(30)  NOT NULL,
  change_reason    VARCHAR2(300) NOT NULL,
  change_timestamp TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_INV_STATUS_HISTORY PRIMARY KEY (history_id),
  CONSTRAINT FK_INVHST_COMPLAINT   FOREIGN KEY (complaint_id)
      REFERENCES TB_CPL_COMPLAINT (complaint_id),
  CONSTRAINT FK_INVHST_OFFICER     FOREIGN KEY (officer_cip)
      REFERENCES TB_STAFF_OFFICER (officer_cip),
  CONSTRAINT CK_INVHST_NEW_STATUS  CHECK (new_status IN
      ('REGISTRADO','VALIDADO_COMISARIA','EN_INVESTIGACION',
       'INTERVENCION_PROGRAMADA','DERIVADO_FISCALIA','ARCHIVADO','RESUELTO')),
  CONSTRAINT CK_INVHST_PREV_STATUS CHECK (previous_status IS NULL OR previous_status IN
      ('REGISTRADO','VALIDADO_COMISARIA','EN_INVESTIGACION',
       'INTERVENCION_PROGRAMADA','DERIVADO_FISCALIA','ARCHIVADO','RESUELTO')),
  CONSTRAINT CK_INVHST_DIFF_STATUS CHECK (previous_status IS NULL OR previous_status <> new_status),
  CONSTRAINT CK_INVHST_REASON      CHECK (TRIM(change_reason) IS NOT NULL)
);
CREATE INDEX IX_INVHST_COMPLAINT ON TB_INV_STATUS_HISTORY (complaint_id, change_timestamp);
CREATE INDEX IX_INVHST_OFFICER   ON TB_INV_STATUS_HISTORY (officer_cip);

-- 1.4 Operativo (cabecera)
CREATE TABLE TB_OPS_OPERATION (
  operation_id   NUMBER(10)   GENERATED BY DEFAULT ON NULL AS IDENTITY,
  sector_id      NUMBER(8)    NOT NULL,
  operation_type VARCHAR2(40) NOT NULL,
  operation_date TIMESTAMP    NOT NULL,
  CONSTRAINT PK_OPS_OPERATION PRIMARY KEY (operation_id),
  CONSTRAINT FK_OPSOP_SECTOR  FOREIGN KEY (sector_id)
      REFERENCES TB_TERR_SECTOR (sector_id)
);
CREATE INDEX IX_OPSOP_SECTOR ON TB_OPS_OPERATION (sector_id);

-- 1.5 Operativo <-> Denuncia (M:N), PK compuesta, CASCADE desde el operativo
CREATE TABLE TB_OPS_OPERATION_COMPLAINT (
  operation_id NUMBER(10) NOT NULL,
  complaint_id NUMBER(12) NOT NULL,
  CONSTRAINT PK_OPS_OPERATION_COMPLAINT PRIMARY KEY (operation_id, complaint_id),
  CONSTRAINT FK_OPSOC_OPERATION FOREIGN KEY (operation_id)
      REFERENCES TB_OPS_OPERATION (operation_id) ON DELETE CASCADE,
  CONSTRAINT FK_OPSOC_COMPLAINT FOREIGN KEY (complaint_id)
      REFERENCES TB_CPL_COMPLAINT (complaint_id)
);
CREATE INDEX IX_OPSOC_COMPLAINT ON TB_OPS_OPERATION_COMPLAINT (complaint_id);

-- 1.6 Operativo <-> Efectivo (M:N), CASCADE desde el operativo
CREATE TABLE TB_OPS_OPERATION_STAFF (
  operation_id NUMBER(10)   NOT NULL,
  officer_cip  VARCHAR2(15) NOT NULL,
  CONSTRAINT PK_OPS_OPERATION_STAFF PRIMARY KEY (operation_id, officer_cip),
  CONSTRAINT FK_OPSOS_OPERATION FOREIGN KEY (operation_id)
      REFERENCES TB_OPS_OPERATION (operation_id) ON DELETE CASCADE,
  CONSTRAINT FK_OPSOS_OFFICER   FOREIGN KEY (officer_cip)
      REFERENCES TB_STAFF_OFFICER (officer_cip)
);
CREATE INDEX IX_OPSOS_OFFICER ON TB_OPS_OPERATION_STAFF (officer_cip);
